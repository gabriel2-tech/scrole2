import 'dart:io';

import 'package:flutter/material.dart';
import 'package:get/get.dart';
import 'package:image_picker/image_picker.dart';
import 'package:scrole/app/service_global/media_service.dart' show MediaService;

import '../../../centre/models/news/create_community_request.dart';
import '../../../centre/models/news/create_community_result.dart';
import '../../../centre/services/community_service.dart';

enum CommunityCreationStatus { idle, loading, success, error }

class CommunityCreationController extends GetxController {
  final CommunityService _service;
  final MediaService _mediaService;

  CommunityCreationController(this._service, {MediaService? mediaService})
      : _mediaService = mediaService ?? Get.find<MediaService>();

  final formKey = GlobalKey<FormState>();
  final nameController = TextEditingController();
  final slugController = TextEditingController();
  final descriptionController = TextEditingController();
  final visibility = 'public'.obs;

  final avatarImage = Rxn<File>();
  final bannerImage = Rxn<File>();
  final status = CommunityCreationStatus.idle.obs;
  final errorMessage = Rxn<String>();
  final result = Rxn<CreateCommunityResult>();

  bool _isSlugAutoGenerated = true;

  bool get isLoading => status.value == CommunityCreationStatus.loading;

  @override
  void onInit() {
    super.onInit();
    nameController.addListener(_onNameChanged);
    slugController.addListener(() {
      if (slugController.text.isEmpty) {
        _isSlugAutoGenerated = true;
      }
    });
    ever(status, _onStatusChanged);
  }

  @override
  void onClose() {
    nameController.dispose();
    slugController.dispose();
    descriptionController.dispose();
    super.onClose();
  }

  void _onNameChanged() {
    if (_isSlugAutoGenerated) {
      final name = nameController.text.trim();
      final generated = name
          .toLowerCase()
          .replaceAll(RegExp(r'[^a-z0-9\s-]'), '')
          .replaceAll(RegExp(r'\s+'), '-')
          .trim();
      slugController.text = generated;
    }
  }

  void onSlugManualEdit(String value) {
    _isSlugAutoGenerated = false;
  }

  void _onStatusChanged(CommunityCreationStatus s) {
    if (s == CommunityCreationStatus.success) {
      final id = result.value?.community.id;
      Get.snackbar(
        'community_create_success_title'.tr,
        'community_create_success_msg'.tr,
        snackPosition: SnackPosition.BOTTOM,
        backgroundColor: Colors.black87,
        colorText: Colors.white,
        duration: const Duration(seconds: 4),
      );
      if (id != null) {
        Get.offNamed('/communities/$id');
      }
    } else if (s == CommunityCreationStatus.error) {
      final msg = errorMessage.value;
      if (msg != null && msg.isNotEmpty) {
        Get.snackbar(
          'error'.tr,
          msg,
          snackPosition: SnackPosition.BOTTOM,
          backgroundColor: Colors.red.shade900,
          colorText: Colors.white,
          duration: const Duration(seconds: 4),
        );
      }
    }
  }

  static final _slugPattern = RegExp(r'^[a-z0-9]+(?:-[a-z0-9]+)*$');

  String? validateName(String? value) {
    final v = (value ?? '').trim();
    if (v.isEmpty) return 'community_name_required'.tr;
    if (v.length > 100) return 'community_name_too_long'.tr;
    return null;
  }

  String? validateSlug(String? value) {
    final v = (value ?? '').trim();
    if (v.isEmpty) return 'community_slug_required'.tr;
    if (v.length > 120) return 'community_slug_too_long'.tr;
    if (!_slugPattern.hasMatch(v)) return 'community_slug_invalid_format'.tr;
    return null;
  }

  String? validateDescription(String? value) {
    final v = (value ?? '').trim();
    if (v.isEmpty) return 'community_description_required'.tr;
    if (v.length > 1000) return 'community_description_too_long'.tr;
    return null;
  }

  Future<void> pickAvatar(ImageSource source) async {
    try {
      final file = await _mediaService.pickProfileImage(source: source);
      if (file != null) avatarImage.value = file;
    } catch (e) {
      debugPrint('Erreur sélection avatar communauté: $e');
    }
  }

  Future<void> pickBanner(ImageSource source) async {
    try {
      final file = await _mediaService.pickCoverImage(source: source);
      if (file != null) bannerImage.value = file;
    } catch (e) {
      debugPrint('Erreur sélection bannière communauté: $e');
    }
  }

  void removeAvatar() => avatarImage.value = null;
  void removeBanner() => bannerImage.value = null;

  Future<void> createCommunity() async {
    if (status.value == CommunityCreationStatus.loading) return;
    if (!(formKey.currentState?.validate() ?? false)) return;

    status.value = CommunityCreationStatus.loading;
    errorMessage.value = null;

    try {
      final request = CreateCommunityRequest(
        id: '',
        name: nameController.text.trim(),
        slug: slugController.text.trim(),
        description: descriptionController.text.trim(),
        photoProfile: null,
        photoCover: null,
        visibility: visibility.value,
      );

      result.value = await _service.createCommunity(
        request: request,
        avatarFile: avatarImage.value,
        bannerFile: bannerImage.value,
      );
      status.value = CommunityCreationStatus.success;
    } on CommunityServiceException catch (e) {
      errorMessage.value = e.message;
      status.value = CommunityCreationStatus.error;
    } catch (e) {
      final cleanMsg = e.toString().replaceFirst('Exception: ', '').replaceFirst('PostgrestException: ', '');
      errorMessage.value = cleanMsg.isNotEmpty ? cleanMsg : 'community_create_generic_error'.tr;
      status.value = CommunityCreationStatus.error;
    }
  }
}
